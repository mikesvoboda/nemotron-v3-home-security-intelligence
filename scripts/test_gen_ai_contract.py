"""Tests for scripts/gen-ai-contract.py (WP7.1 drift generator).

House convention: scripts carry an adjacent test_*.py exercising the pure
logic; the CI drift gate itself is `gen-ai-contract.py --check` wired next to
the other generate-*- --check steps. These tests import the script via
importlib from its path (scripts/ is not a package) and never hit the network
or a Triton server.
"""

from __future__ import annotations

