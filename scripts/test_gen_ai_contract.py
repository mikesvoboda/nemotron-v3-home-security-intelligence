import subprocess
import sys
from pathlib import Path

import pytest

REPO_ROOT = Path(__file__).resolve().parents[1]
SCRIPT = REPO_ROOT / "scripts" / "gen-ai-contract.py"


def _load():
    spec = importlib.util.spec_from_file_location("gen_ai_contract", SCRIPT)
    assert spec and spec.loader
    mod = importlib.util.module_from_spec(spec)
    # register BEFORE exec: dataclass string-annotation resolution looks the
    # defining module up in sys.modules (AttributeError on None otherwise)
    sys.modules["gen_ai_contract"] = mod
    spec.loader.exec_module(mod)
    return mod


gen = _load()


