def _rng_for(*parts: object) -> random.Random:
    """Fresh seeded PRNG per call-site path: state never bleeds between
    ops, requests, or tests (pytest-randomly safe), and the seed derives
    only from the parts, not from a counter."""
    digest = hashlib.sha256("|".join(str(p) for p in parts).encode("utf-8")).hexdigest()
    return random.Random(int(digest[:16], 16))  # noqa: S311 - seeded fixture, not security


@lru_cache(maxsize=1)
def _snapshots() -> dict[str, dict[str, Any]]:
    out: dict[str, dict[str, Any]] = {}
    for path in SCHEMA_DIR.glob("*.response.json"):
        op_id = path.name[: -len(".response.json")]
        out[op_id] = json.loads(path.read_text(encoding="utf-8"))
    return out


def snapshot_for(op_id: str) -> dict[str, Any] | None:
    return _snapshots().get(op_id)


def classes_for_profile(profile: str) -> tuple[str, ...]:
    if profile == "security":
        return tuple(sorted(SECURITY_CLASSES))
    return GATEWAY_CLASSES


# --- semantic overrides ---------------------------------------------------
# The plan's shipped-correct bullets: shapes the JSON Schema (type-only)
# cannot express. _OVERRIDES maps (op_id, property) -> (kind, arg); the
# walker consults it BEFORE generic generation.


def _unit_embedding(dim: int, *parts: object) -> list[float]:
    rng = _rng_for("embedding", dim, *parts)
    raw = [rng.uniform(-1.0, 1.0) for _ in range(dim)]
    norm = math.sqrt(sum(v * v for v in raw))
    return [v / norm for v in raw]


def _class_name(profile: str, i: int, op_id: str) -> str:
    table = classes_for_profile(profile)
    rng = _rng_for("class", profile, i, op_id)
    return table[rng.randrange(len(table))]


def _confidence(i: int, op_id: str) -> float:
    rng = _rng_for("conf", i, op_id)
    return round(rng.uniform(0.55, 0.97), 4)


def _yolo_bbox_dict(i: int, op_id: str) -> dict[str, int]:
    """DICT of INTS, absolute pixels, in-frame (WP7.4 deployed shape:
    {x,y,width,height}; clamping is the gateway's job, the fake just stays
    inside the frame so it is always clamp-valid)."""
    rng = _rng_for("yolobbox", i, op_id)
    w, h = _FAKE_FRAME
    bw = rng.randint(24, 180)
    bh = rng.randint(24, 150)
    return {
        "x": rng.randint(0, w - bw),
        "y": rng.randint(0, h - bh),
        "width": bw,
        "height": bh,
    }


