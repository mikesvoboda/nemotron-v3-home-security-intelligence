# --- generic snapshot walker ----------------------------------------------


def _resolve(node: dict[str, Any], ctx: dict[str, Any]) -> tuple[dict[str, Any], str]:
    """Follow $ref chains; return (node, def_name). The def name qualifies
    property overrides so an op carrying TWO different bbox definitions
    (historically analyze_scene: CaptionedRegion 4-coord AND OCRRegion
    8-coord - A7.2 deleted that op; the qualification mechanism stays) can pin
    each - a bare-name match alone could not tell them apart."""
    def_name = ""
    while "$ref" in node:
        def_name = node["$ref"].rsplit("/", 1)[-1]
        node = ctx["defs"][def_name]
    return node, def_name


def _gen_value(  # noqa: PLR0911 - one return per JSON-Schema type is the shape of a type dispatcher
    node: dict[str, Any], name: str, ctx: dict[str, Any], i: int = 0, qual: str = ""
) -> Any:
    """Generate a schema-valid value for one property. Deterministic: every
    branch consumes only the (op_id, name, i) seed path carried in ctx."""
    op_id = ctx["op_id"]
    qualified = f"{qual}.{name}" if qual else name
    override = _OVERRIDES.get((op_id, qualified)) or _OVERRIDES.get((op_id, name))
    if override is not None:
        kind, arg = override
        if kind == "unit_embedding":
            return _unit_embedding(arg, op_id)
        if kind == "const":
            return arg
        raise ValueError(f"{op_id}: unknown override kind {kind}")
    node, def_name = _resolve(node, ctx)
    qual = def_name or qual
    if "anyOf" in node:
        # Deterministic branch choice: NULLABLE schemas here are genuinely
        # optional metadata (ensemble_metadata) - pick the non-null branch,
        # never the null one, so the fake exercises the populated shape.
        branches = [b for b in node["anyOf"] if b.get("type") != "null"] or node["anyOf"]
        return _gen_value(branches[0], name, ctx, i, qual)
    if "enum" in node:
        return node["enum"][0]
    t = node.get("type")
    if t == "number":
        if name == "inference_time_ms":
            return _FAKE_INFERENCE_MS
        if name == "total_inference_time_ms":
            return _FAKE_TOTAL_MS
        return round(_rng_for(op_id, qualified, i, "num").uniform(0.1, 0.9), 4)
    if t == "integer":
        return _rng_for(op_id, qualified, i, "int").randint(1, 8)
    if t == "boolean":
        return _rng_for(op_id, qualified, i, "bool").random() < 0.5
    if t == "string":
        return f"{name}_{_rng_for(op_id, qualified, i, 'str').randint(100, 999)}"
    if t == "array":
        return _gen_array(node, name, ctx, qual)
    if t == "object":
        if "properties" in node:
            return {k: _gen_value(v, k, ctx, 0, qual) for k, v in node["properties"].items()}
        # free-form object (scores/similarities/enrichments maps)
        rng = _rng_for(op_id, qualified, "free-obj")
        return {
            "alpha": round(rng.uniform(0.1, 0.9), 4),
            "bravo": round(rng.uniform(0.1, 0.9), 4),
        }
    raise ValueError(f"{op_id}: cannot generate value for schema {node!r} (name {name})")


def _gen_array(node: dict[str, Any], name: str, ctx: dict[str, Any], qual: str = "") -> list[Any]:
    items = node.get("items", {})
    item_type, _ = _resolve(items, ctx)
    count = 2 if item_type.get("type") != "string" else 1
    # minItems (e.g. a 4-coord bbox array) outranks the default 2 - a
    # shorter instance violates the snapshot we validate against.
    count = max(count, node.get("minItems") or 1)
    return [_gen_value(items, f"{name}.{i}", ctx, i, qual) for i in range(count)]


def generate_from_snapshot(op_id: str, profile: str = "gateway") -> dict[str, Any] | list[Any]:
    schema = snapshot_for(op_id)
    if schema is None:
        raise KeyError(f"{op_id} has no committed response snapshot - use the literal generator")
    ctx = {"op_id": op_id, "defs": schema.get("$defs", {}), "profile": profile}
    result = _gen_value(schema, op_id, ctx)
    if not isinstance(result, dict | list):
        raise TypeError(f"{op_id}: snapshot produced {type(result)}")
    return result


def create_response_bytes(obj: Any) -> bytes:
    """The ONE serializer. sort_keys + compact separators = the byte-identity
    mechanism; dict insertion order cannot leak, whitespace cannot vary."""
    return json.dumps(obj, sort_keys=True, separators=(",", ":")).encode("utf-8")


