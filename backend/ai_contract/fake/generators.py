def generate(op_id: str, payload: Any = None, profile: str = "gateway") -> Any:
    """The one entry point: the GEN_GAPS ops route to the literal
    deployed-shape generator; the rest are WALKED from their committed
    snapshot. Both paths are schema-VALIDATED post-generation (validate()
    below) so the schema-driven guarantee holds for every op in the registry:
    a snapshot edit that makes the fake's output nonconformant reddens the
    suite either way."""
    value: Any
    if op_id in _LITERAL_OPS:
        value = _literal_generate(op_id, payload, profile)
    elif snapshot_for(op_id) is not None:
        value = generate_from_snapshot(op_id, profile)
    else:
        raise KeyError(f"{op_id}: no snapshot and not a literal op")
    if op_id == "vlm_assess" and isinstance(payload, dict):
        images = payload.get("image_paths")
        if isinstance(images, list) and images and all(isinstance(x, str) for x in images):
            # spec §3 Slots: "The FakeProvider returns a deterministic verdict
            # keyed on an image hash." The walk seeds op+profile only, so the
            # verdict fields are re-drawn from the image paths themselves -
            # same images replay identically (pure function of the parts),
            # different images can differ (the failure-ladder fixtures need
            # verdict variety). Keys are paths, never bytes (D10).
            rng = _rng_for(op_id, "|".join(images), profile, "verdict")
            value["verdict"] = rng.choice(["confirmed", "rejected", "uncertain"])
            value["risk_score"] = rng.randint(0, 100)
    validate(op_id, value)
    return value


def validate(op_id: str, value: Any) -> None:
    """Validate a generated response against the committed snapshot. The
    fake failing its OWN contract here is a loud bug, never a silent drift."""
    import jsonschema

    schema = snapshot_for(op_id)
    if schema is None:
        return
    jsonschema.validate(value, schema)
